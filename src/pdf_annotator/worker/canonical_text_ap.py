"""Strict PyMuPDF-native FreeText appearance patching.

The parent appearance is always generated by PyMuPDF.  This module accepts
only the narrow, pinned 1.28.2 text slot that follows PyMuPDF's generated
clip.  It replaces that one ``BT … ET`` with a child text Form; it is
deliberately *not* a PDF content-stream parser or a callout renderer.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
import re
from typing import Any

from ..domain.rich_text import RichText


class CanonicalTextPatchError(RuntimeError):
    """The native AP was not the one production shape we have validated."""


_ASSETS = Path(__file__).parents[1] / "assets" / "fonts"
_FONTS = {
    ("Helvetica", False, False): ("FSource", _ASSETS / "SourceSans3-Regular.ttf"),
    ("Helvetica", True, False): ("FSourceBold", _ASSETS / "SourceSans3-Bold.ttf"),
    ("Helvetica", False, True): ("FSourceItalic", _ASSETS / "SourceSans3-Italic.ttf"),
    ("Helvetica", True, True): ("FSourceBoldItalic", _ASSETS / "SourceSans3-BoldItalic.ttf"),
    ("Courier", False, False): ("FCourier", _ASSETS / "CourierPrime-Regular.ttf"),
    ("Courier", True, False): ("FCourierBold", _ASSETS / "CourierPrime-Bold.ttf"),
    ("Courier", False, True): ("FCourierItalic", _ASSETS / "CourierPrime-Italic.ttf"),
    ("Courier", True, True): ("FCourierBoldItalic", _ASSETS / "CourierPrime-BoldItalic.ttf"),
}
_NUMBER = r"[+-]?(?:\d+\.?\d*|\.\d+)"
_TEXT_RUN = (
    r"/(?P<font>[A-Za-z0-9_.+-]+)[ \t]+(?P<size>" + _NUMBER + r")[ \t]+Tf[ \t]*\r?\n"
    r"(?P<matrix>" + _NUMBER + r"[ \t]+" + _NUMBER + r"[ \t]+" + _NUMBER + r"[ \t]+"
    + _NUMBER + r"[ \t]+" + _NUMBER + r"[ \t]+" + _NUMBER + r")[ \t]+Tm[ \t]*\r?\n"
    r"\[[^\]]+\]TJ[ \t]*\r?\n"
)
_TEXT_COLOR = r"(?:" + _NUMBER + r")[ \t]+(?:" + _NUMBER + r")[ \t]+(?:" + _NUMBER + r")[ \t]+rg[ \t]*\r?\n"
_TEXT_LINE_ADVANCE = (r"(?:" + _NUMBER + r")[ \t]+(?:" + _NUMBER + r")[ \t]+Td[ \t]*\r?\n"
                      r"\[[^\]]+\]TJ[ \t]*\r?\n")
# This accepts two—and only two—observed PyMuPDF generated forms: explicit
# ``Tf/Tm/TJ`` runs, and its deterministic wrapped continuation ``Td/TJ``.
# It is intentionally not a general content-stream parser.
_TEXT_OBJECT = re.compile(r"(?P<text>BT[ \t]*\r?\n(?P<body>(?:" + _TEXT_RUN + "|" + _TEXT_COLOR
                          + "|" + _TEXT_LINE_ADVANCE + r")+)ET)", re.ASCII)
_TEXT_RUN_RE = re.compile(_TEXT_RUN, re.ASCII)
_LOCAL_TRANSFORM = re.compile(
    r"1[ \t]+0[ \t]+(?:-?0)[ \t]+1[ \t]+(?P<x>" + _NUMBER + r")[ \t]+(?P<y>" + _NUMBER + r")[ \t]+cm[ \t]*\r?\n"
    r"1[ \t]+0[ \t]+0[ \t]+-1[ \t]+(?:-?0)[ \t]+(?P<h>" + _NUMBER + r")[ \t]+cm[ \t]*\r?\n"
    r"q[ \t]*\r?\n(?P<clip_x>" + _NUMBER + r")[ \t]+(?P<clip_y>" + _NUMBER + r")[ \t]+"
    r"(?P<clip_w>\d+(?:\.\d+)?)[ \t]+(?P<clip_h>\d+(?:\.\d+)?)[ \t]+re[ \t]*\r?\nW[ \t]+n[ \t]*\r?\n"
    r"(?:" + _NUMBER + r")[ \t]+(?:" + _NUMBER + r")[ \t]+(?:" + _NUMBER + r")[ \t]+rg[ \t]*\r?\n$", re.ASCII)
_NORMAL_AP = re.compile(r"/N\s+(\d+)\s+0\s+R")


@dataclass(frozen=True, slots=True)
class _Slot:
    start: int
    end: int
    x: float
    y: float
    clip_width: float
    height: float


@dataclass(frozen=True, slots=True)
class _StyledPiece:
    """One contiguous semantic span with the child Form font that paints it."""
    resource: str
    font_xref: int
    size: float
    text: str


def _number(value: float) -> str:
    return f"{value:.5f}".rstrip("0").rstrip(".") or "0"


def _normal_xref(document: Any, annotation_xref: int) -> int:
    kind, ap = document.xref_get_key(annotation_xref, "AP")
    match = _NORMAL_AP.search(ap) if kind == "dict" else None
    if match is None:
        raise CanonicalTextPatchError("PyMuPDF did not create one normal appearance Form")
    return int(match.group(1))


def _slot(stream: str) -> _Slot:
    matches = list(_TEXT_OBJECT.finditer(stream))
    if len(matches) != 1:
        raise CanonicalTextPatchError("Expected exactly one generated FreeText text object")
    match = matches[0]
    runs = list(_TEXT_RUN_RE.finditer(match.group("body")))
    if not runs:
        raise CanonicalTextPatchError("Generated text object has no supported text run")
    matrices = [tuple(float(value) for value in run.group("matrix").split()) for run in runs]
    if any(matrix[:4] != (1.0, 0.0, 0.0, -1.0) for matrix in matrices):
        raise CanonicalTextPatchError("Unexpected generated text matrix")
    transform = _LOCAL_TRANSFORM.search(stream[:match.start()])
    if transform is None or transform.end() != match.start():
        raise CanonicalTextPatchError("Expected the known generated FreeText clip before text")
    if stream[match.end():].strip() not in ("Q", "Q\nQ"):
        raise CanonicalTextPatchError("Unexpected content after generated FreeText text")
    width, height = float(transform.group("clip_w")), float(transform.group("h"))
    if width <= 0 or height <= 0:
        raise CanonicalTextPatchError("Generated FreeText local space is degenerate")
    return _Slot(match.start(), match.end(), matrices[0][4], matrices[0][5], width, height)


def _font(page: Any, run) -> tuple[str, int]:
    # Times is an app-created legacy role. For imported text it is an
    # alternative family and therefore intentionally becomes Courier Prime.
    role = "Helvetica" if run.font_family == "Helvetica" else "Courier"
    resource, path = _FONTS[(role, run.bold, run.italic)]
    if not path.is_file():
        raise CanonicalTextPatchError(f"Missing bundled canonical font: {path.name}")
    return resource, page.insert_font(fontname=resource, fontfile=str(path))


def _encode(document: Any, font_xref: int, text: str) -> str:
    widths = document.get_char_widths(font_xref, max((ord(char) for char in text), default=0) + 1)
    result: list[str] = []
    for character in text:
        glyph, _width = widths[ord(character)]
        if glyph <= 0:
            raise CanonicalTextPatchError(f"Canonical font lacks U+{ord(character):04X}")
        result.append(f"{glyph:04X}")
    return "<" + "".join(result) + ">"


def _advance(document: Any, font_xref: int, text: str, size: float) -> float:
    widths = document.get_char_widths(font_xref, max((ord(char) for char in text), default=0) + 1)
    total = 0.0
    for character in text:
        glyph, width = widths[ord(character)]
        if glyph <= 0:
            raise CanonicalTextPatchError(f"Canonical font lacks U+{ord(character):04X}")
        total += width * size
    return total


def _semantic_tokens(rich_text: RichText,
                     fonts: dict[tuple[str, bool, bool], tuple[str, int]]) -> list[tuple[str, tuple[_StyledPiece, ...]]]:
    """Split rich text into words, whitespace and explicit paragraph breaks.

    The token accumulator crosses rich-run boundaries, so a word whose style
    changes mid-word is still measured and wrapped as one semantic token.
    """
    tokens: list[tuple[str, tuple[_StyledPiece, ...]]] = []
    current_kind: str | None = None
    current: list[_StyledPiece] = []

    def append(kind: str, piece: _StyledPiece) -> None:
        nonlocal current_kind, current
        if current_kind != kind:
            if current_kind is not None:
                tokens.append((current_kind, tuple(current)))
            current_kind, current = kind, []
        if current and current[-1].resource == piece.resource and current[-1].font_xref == piece.font_xref \
                and current[-1].size == piece.size:
            previous = current[-1]
            current[-1] = _StyledPiece(previous.resource, previous.font_xref, previous.size,
                                        previous.text + piece.text)
        else:
            current.append(piece)

    cr_pending = False
    for run in rich_text.runs:
        role = "Helvetica" if run.font_family == "Helvetica" else "Courier"
        resource, font_xref = fonts[(role, run.bold, run.italic)]
        for character in run.text:
            if cr_pending:
                cr_pending = False
                if character == "\n":
                    continue
            if character == "\r":
                character, cr_pending = "\n", True
            kind = "break" if character == "\n" else "space" if character.isspace() else "word"
            append(kind, _StyledPiece(resource, font_xref, run.font_size, character))
    if current_kind is not None:
        tokens.append((current_kind, tuple(current)))
    return tokens


def _pieces(document: Any, fonts: dict[tuple[str, bool, bool], tuple[str, int]], slot: _Slot,
            rich_text: RichText) -> list[str]:
    """Paint deterministic word-aware rich text in the isolated child Form.

    Ordinary words move as indivisible semantic tokens, even across rich-run
    boundaries. A character-level split is used only for one token too wide
    for an otherwise empty line. Explicit CR, LF and CRLF become exactly one
    line advance; they remain unchanged in the annotation's /Contents and /RC.
    """
    pieces = ["BT"]
    x, y, line_height = slot.x, slot.y, 0.0
    line: list[_StyledPiece] = []
    pending_space: list[_StyledPiece] = []

    def width(parts: tuple[_StyledPiece, ...] | list[_StyledPiece]) -> float:
        return sum(_advance(document, part.font_xref, part.text, part.size) for part in parts)

    def append(parts: tuple[_StyledPiece, ...] | list[_StyledPiece]) -> None:
        nonlocal line_height
        line.extend(parts)
        if parts:
            line_height = max(line_height, *(part.size * 1.28 for part in parts))

    def flush() -> None:
        nonlocal x
        for part in line:
            if not part.text:
                continue
            pieces.extend((f"/{part.resource} {_number(part.size)} Tf",
                           f"1 0 0 -1 {_number(x)} {_number(y)} Tm",
                           f"{_encode(document, part.font_xref, part.text)} Tj"))
            x += _advance(document, part.font_xref, part.text, part.size)

    def newline(fallback_size: float) -> None:
        nonlocal x, y, line_height, line
        flush()
        x, y = slot.x, y + (line_height or fallback_size * 1.28)
        line_height, line = 0.0, []

    def emergency(parts: tuple[_StyledPiece, ...]) -> None:
        """Break a single overlong token only after it owns an empty line."""
        for part in parts:
            for character in part.text:
                glyph = _StyledPiece(part.resource, part.font_xref, part.size, character)
                if line and width(line) + width((glyph,)) > slot.clip_width:
                    newline(part.size)
                append((glyph,))

    for kind, token in _semantic_tokens(rich_text, fonts):
        fallback_size = token[0].size
        if kind == "break":
            # Spaces before an explicit source paragraph break are semantic;
            # only spaces consumed by an automatic wrap are discarded.
            append(pending_space)
            pending_space = []
            newline(fallback_size)
            continue
        if kind == "space":
            if line:
                pending_space.extend(token)
            else:
                # Preserve actual paragraph-leading whitespace. It was not a
                # wrap opportunity and must not be silently collapsed.
                append(token)
            continue

        word_width = width(token)
        candidate = [*pending_space, *token] if line else list(token)
        if line and width(line) + width(candidate) <= slot.clip_width:
            append(candidate)
        elif line:
            # The pending whitespace is the line-break opportunity and must
            # not become a synthetic leading space on the visual next line.
            pending_space = []
            newline(fallback_size)
            if word_width <= slot.clip_width:
                append(token)
            else:
                emergency(token)
        elif word_width <= slot.clip_width:
            append(token)
        else:
            emergency(token)
        pending_space = []

    append(pending_space)
    flush()
    pieces.extend(("ET", ""))
    return pieces


def _child(document: Any, page: Any, slot: _Slot, rich_text: RichText) -> int:
    keys = {("Helvetica" if run.font_family == "Helvetica" else "Courier", run.bold, run.italic)
            for run in rich_text.runs}
    # ``Page.insert_font`` is the public Type0 / Identity-H factory, but it
    # briefly adds its resources to the page. The child owns the resulting
    # font xrefs, so restore the page and its direct resource dictionary before
    # returning: no external page resource is normalized as a side effect.
    page_before = document.xref_object(page.xref)
    resource_before: tuple[int, str] | None = None
    resource_kind, resource_value = document.xref_get_key(page.xref, "Resources")
    resource_ref = re.fullmatch(r"(\d+)\s+0\s+R", resource_value) if resource_kind == "xref" else None
    if resource_ref is not None:
        resource_xref = int(resource_ref.group(1))
        resource_before = resource_xref, document.xref_object(resource_xref)
    try:
        fonts = {key: _font(page, type("Run", (), {"font_family": key[0], "bold": key[1], "italic": key[2]})())
                 for key in keys}
    finally:
        document.update_object(page.xref, page_before)
        if resource_before is not None:
            document.update_object(*resource_before)
    stream = "\n".join(_pieces(document, fonts, slot, rich_text)).encode("ascii")
    resources = " ".join(f"/{name} {xref} 0 R" for name, xref in fonts.values())
    xref = document.get_new_xref()
    document.update_object(xref, "<< /Type /XObject /Subtype /Form /FormType 1 "
                           f"/BBox [0 0 {_number(slot.clip_width + 10)} {_number(slot.height)}] "
                           f"/Resources << /Font << {resources} >> >> /Length {len(stream)} >>")
    document.update_stream(xref, stream)
    return xref


def _with_child_resource(parent: str, child_xref: int) -> str:
    marker = "/Resources <<"
    if parent.count(marker) != 1 or "/CanonicalText" in parent:
        raise CanonicalTextPatchError("Unsupported parent resource dictionary")
    return parent.replace(marker, marker + f" /XObject << /CanonicalText {child_xref} 0 R >>", 1)


def patch_native_freetext_appearance(document: Any, page: Any, annotation_xref: int,
                                     rich_text: RichText) -> None:
    """Patch exactly one fresh PyMuPDF AP, leaving its geometry byte-for-byte.

    Callers must rollback the annotation root if this raises. The newly
    allocated child/font objects are unreachable after rollback and cannot
    affect the original external annotation.
    """
    parent_xref = _normal_xref(document, annotation_xref)
    parent = document.xref_object(parent_xref)
    stream = document.xref_stream(parent_xref).decode("ascii")
    slot = _slot(stream)
    bbox_before = document.xref_get_key(parent_xref, "BBox")
    matrix_before = document.xref_get_key(parent_xref, "Matrix")
    child = _child(document, page, slot, rich_text)
    replacement = "q\n/CanonicalText Do\nQ"
    patched_stream = stream[:slot.start] + replacement + stream[slot.end:]
    document.update_object(parent_xref, _with_child_resource(parent, child))
    document.update_stream(parent_xref, patched_stream.encode("ascii"))
    if (document.xref_get_key(parent_xref, "BBox") != bbox_before
            or document.xref_get_key(parent_xref, "Matrix") != matrix_before
            or stream[:slot.start] + stream[slot.end:] !=
            patched_stream[:slot.start] + patched_stream[slot.start + len(replacement):]):
        raise CanonicalTextPatchError("Canonical text patch changed native parent geometry")
