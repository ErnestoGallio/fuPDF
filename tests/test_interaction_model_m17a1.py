def _click_native_text(view, character_index: int) -> None:
    character = tuple(character for chunk in view.text_layer.loaded_chunks(0)
                      for character in chunk.characters)[character_index]
    QTest.mouseClick(view.viewport(), Qt.MouseButton.LeftButton,
                     pos=_viewport_point(view, 0, character))


def _right_click_native_text(view, point: QPoint) -> None:
    """Send the actual viewport ContextMenu event generated by a mouse click."""
    event = QContextMenuEvent(QContextMenuEvent.Reason.Mouse, point,
                              view.viewport().mapToGlobal(point))
    QApplication.sendEvent(view.viewport(), event)


