def test_caret_esc_and_tab_change_clear_only_the_transient_target(m17_window, tmp_path, pdf_fixture_copy):
    window, path = m17_window
    first, view = _open(window, path)
    _click_native_text(view, 0)
    wait_until(lambda: view.text_layer.insertion is not None)
    view.setFocus()
    QTest.keyClick(view, Qt.Key.Key_Escape)
    assert view.text_layer.insertion is None and view.text_layer.insertion_preview is None

    _click_native_text(view, 1)
    wait_until(lambda: view.text_layer.insertion is not None)
    view.set_text_box_enabled(True)
    assert view.text_layer.insertion is None and view.text_layer.insertion_preview is None
    view.set_text_box_enabled(False)

    _click_native_text(view, 1)
    wait_until(lambda: view.text_layer.insertion is not None)
    second_path = tmp_path / "m17-second.pdf"
    pdf_fixture_copy(second_path)
    _open(window, second_path)
    assert window.manager.active_id != first.document_id
    assert view.text_layer.insertion is None and view.text_layer.insertion_preview is None
    assert first.document_revision == 0


def test_double_click_word_model_excludes_punctuation_and_keeps_internal_joiners():
    """The pure controller test fixes the deterministic word-unit contract."""
    chunk = _chunk(text="(rete) computer, l'arte pre-stampa PDF.")
    cache = TextSnapshotCache()
    cache.put(_index(chunk)); cache.put(chunk)
    session = type("Session", (), {"document_id": chunk.document_id,
                                     "document_generation": 1,
                                     "lifecycle": Lifecycle.READY})()
    controller = TextSelectionController(session, cache, lambda: None, lambda _error: None)
    for expected, index in (("rete", 2), ("computer", 9), ("l'arte", 20),
                            ("pre-stampa", 29), ("PDF", 36)):
        character = chunk.characters[index]
        point = PdfPoint((character.quad.upper_left.x + character.quad.upper_right.x) / 2,
                         (character.quad.upper_left.y + character.quad.lower_left.y) / 2)
        assert controller.select_word(0, point)
        assert controller.provisional is not None
        assert controller.provisional.text == expected
