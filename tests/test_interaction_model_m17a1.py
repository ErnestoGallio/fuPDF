def test_viewport_right_click_mouse_action_opens_and_confirms_existing_m11_insert(m17_window):
    _window, path = m17_window
    session, view = _open(_window, path)
    character = view.text_layer.loaded_chunks(0)[0].characters[2]
    point = _viewport_point(view, 0, character)
    _right_click_native_text(view, point)
    wait_until(lambda: view._insert_context_menu is not None)
    menu = view._insert_context_menu
    assert menu is not None
    action, = menu.actions()
    assert action.text() == "Inserisci testo" and action.isEnabled()
    wait_until(lambda: view.text_layer.insertion is not None)
    target = view.text_layer.insertion

    # This is deliberately a real click on the visible QMenu action. Calling
    # QAction.trigger() directly used to reverse QMenu's hide/trigger ordering
    # and masked the runtime target-loss regression.
    QTest.mouseClick(menu, Qt.MouseButton.LeftButton, pos=menu.actionGeometry(action).center())
    wait_until(lambda: view._editorial_editor is not None)
    assert view._editing_editorial_target == target
    view._editorial_editor.setPlainText("inserito")
    QTest.keyClick(view._editorial_editor, Qt.Key.Key_Return,
                   Qt.KeyboardModifier.ControlModifier)
    wait_until(lambda: session.document_revision == 1)
    created, = session.annotations.values()
    assert created.kind == AnnotationKind.INSERT_TEXT
    assert created.target == target
    assert created.text == "inserito"


