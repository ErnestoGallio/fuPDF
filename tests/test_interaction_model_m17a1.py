def test_native_single_click_resolves_punctuation_and_whitespace_as_boundaries(m17_window):
    _window, path = m17_window
    _session, view = _open(_window, path)
    characters = tuple(character for chunk in view.text_layer.loaded_chunks(0)
                       for character in chunk.characters)
    for index in (next(i for i, character in enumerate(characters) if character.text == " "),
                  next(i for i, character in enumerate(characters) if character.text == ".")):
        _click_native_text(view, index)
        wait_until(lambda: view.text_layer.insertion is not None)
        assert view.text_layer.confirmed is None
        assert view.text_layer.insertion.char_index == characters[index].index


def test_pointer_jitter_keeps_caret_but_drag_starts_existing_m6_range(m17_window):
    _window, path = m17_window
    _session, view = _open(_window, path)
    characters = tuple(character for chunk in view.text_layer.loaded_chunks(0)
                       for character in chunk.characters)
    begin = _viewport_point(view, 0, characters[0])
    QTest.mousePress(view.viewport(), Qt.MouseButton.LeftButton, pos=begin)
    jitter = begin + QPoint(1, 1)
    QTest.mouseMove(view.viewport(), jitter, delay=1)
    QTest.mouseRelease(view.viewport(), Qt.MouseButton.LeftButton, pos=jitter)
    wait_until(lambda: view.text_layer.insertion is not None)
    assert view.text_layer.confirmed is None

    _drag(view, 0, 4)
    assert view.text_layer.insertion is None
    assert view.text_layer.insertion_preview is None
    assert view.text_layer.confirmed is not None


