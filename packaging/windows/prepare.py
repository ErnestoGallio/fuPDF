"""Deterministic build resources; uses only the existing Qt dependency."""

from pathlib import Path
from importlib.metadata import version as installed_version
import struct
import sys
import sysconfig
import tomllib

from PySide6.QtCore import QBuffer, QByteArray, QIODevice, QRect, Qt
from PySide6.QtGui import QImage, QPainter


ROOT = Path(__file__).resolve().parents[2]
SIZES = (16, 24, 32, 48, 64, 128, 256)


def check_environment(root: Path = ROOT) -> None:
    if (sys.version_info[:3] != (3, 14, 10)
            or sysconfig.get_platform() != "win-amd64"
            or sysconfig.get_config_var("Py_GIL_DISABLED")):
        raise RuntimeError("Packaging requires standard CPython 3.14.10 for Windows x64")
    project = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))
    requirements = (root / "packaging/windows/requirements-build.txt").read_text().splitlines()
    for requirement in requirements + project["project"]["dependencies"]:
        if not requirement.strip() or requirement.startswith("#"):
            continue
        name, expected = requirement.split("==")
        actual = installed_version(name)
        if actual != expected:
            raise RuntimeError(f"Build requires {name}=={expected}; installed {actual}")


def crop_icon_content(image: QImage) -> QImage:
    image = image.convertToFormat(QImage.Format.Format_RGBA8888)
    pixels = image.constBits()
    width, height = image.width(), image.height()
    left, top, right, bottom = width, height, -1, -1
    for y in range(height):
        start = y * image.bytesPerLine()
        alpha = pixels[start + 3:start + width * 4:4].tobytes()
        visible = alpha.lstrip(b"\x00\x01")
        if visible:
            left = min(left, width - len(visible))
            right = max(right, len(alpha.rstrip(b"\x00\x01")) - 1)
            top = min(top, y)
            bottom = y
    if right < 0:
        raise ValueError("Branding image has no visible content")
    # Alpha 1/255 can be stray noise. Keep a fringe around the visible edge
    # so nearby faint antialiasing is preserved in the resampling.
    bounds = QRect(left, top, right - left + 1, bottom - top + 1)
    return image.copy(bounds.adjusted(-2, -2, 2, 2).intersected(image.rect()))


def icon_bytes(source: Path) -> bytes:
    image = QImage(str(source))
    if image.isNull():
        raise ValueError(f"Cannot decode branding image: {source.name}")
    content = crop_icon_content(image)
    frames = []
    for size in SIZES:
        margin = round(size / 16)
        extent = size - 2 * margin
        scaled = content.scaled(extent, extent, Qt.AspectRatioMode.KeepAspectRatio,
                              Qt.TransformationMode.SmoothTransformation)
        canvas = QImage(size, size, QImage.Format.Format_ARGB32)
        # Do not let QApplication / screen DPI change PNG pHYs metadata.
        canvas.setDotsPerMeterX(3780)
        canvas.setDotsPerMeterY(3780)
        canvas.fill(Qt.GlobalColor.transparent)
        painter = QPainter(canvas)
        painter.drawImage((size - scaled.width()) // 2, (size - scaled.height()) // 2, scaled)
        painter.end()
        data = QByteArray()
        buffer = QBuffer(data)
        buffer.open(QIODevice.OpenModeFlag.WriteOnly)
        if not canvas.save(buffer, "PNG"):
            raise RuntimeError("Cannot encode ICO frame")
        frames.append(bytes(data))
    # Windows ICO supports PNG frames. Width/height byte 0 denotes 256 pixels.
    offset = 6 + 16 * len(frames)
    entries = []
    for size, frame in zip(SIZES, frames):
        entries.append(struct.pack("<BBBBHHII", size % 256, size % 256, 0, 0,
                                   1, 32, len(frame), offset))
        offset += len(frame)
    return struct.pack("<HHH", 0, 1, len(frames)) + b"".join(entries + frames)


def version_resource(version: str) -> str:
    parts = tuple(int(part) for part in version.split("."))
    if len(parts) != 3 or any(not 0 <= part <= 65535 for part in parts):
        raise ValueError("Windows build requires a three-part numeric project version")
    numeric = parts + (0,)
    return f'''# Generated by prepare.py from pyproject.toml; do not edit.
VSVersionInfo(
  ffi=FixedFileInfo(filevers={numeric!r}, prodvers={numeric!r},
    mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[StringFileInfo([StringTable('040904B0', [
    StringStruct('FileDescription', 'fuPDF'),
    StringStruct('FileVersion', '{version}'),
    StringStruct('OriginalFilename', 'fuPDF.exe'),
    StringStruct('ProductName', 'fuPDF'),
    StringStruct('ProductVersion', '{version}')
  ])]), VarFileInfo([VarStruct('Translation', [1033, 1200])])]
)
'''


def prepare(root: Path = ROOT) -> None:
    assets = root / "src/pdf_annotator/assets"
    required = [assets / "branding/fupdf.png"]
    required += [assets / "fonts" / f"{family}-{style}.ttf"
                 for family in ("SourceSans3", "CourierPrime")
                 for style in ("Regular", "Bold", "Italic", "BoldItalic")]
    required += [assets / "fonts" / name
                 for name in ("SOURCE_SANS_3_LICENSE.md", "COURIER_PRIME_OFL.txt")]
    for path in required:
        if not path.is_file():
            raise FileNotFoundError(f"Required packaging resource missing: {path}")
    (assets / "branding/fupdf.ico").write_bytes(icon_bytes(required[0]))
    project = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))
    (root / "packaging/windows/version_info.txt").write_text(
        version_resource(project["project"]["version"]), encoding="utf-8")


if __name__ == "__main__":
    check_environment()
    prepare()
